class AppError(Exception):
    def __init__(
        self,
        code: int,
        http_status: int,
        message: str,
        data: Any = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.http_status = http_status
        self.message = message
        self.data = data
